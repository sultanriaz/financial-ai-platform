def main() -> None:
    parser = argparse.ArgumentParser(description="Apply financial-ai-platform patches")
    parser.add_argument("project_root", nargs="?", default=".",
                        help="Path to project root (default: current directory)")
    parser.add_argument("--whatif", action="store_true",
                        help="Preview changes without writing any files")
    parser.add_argument("--no-backup", action="store_true",
                        help="Skip creating .bak copies of originals")
    args = parser.parse_args()

    root = Path(args.project_root).resolve()

    if not (root / "backend").exists() or not (root / "frontend").exists():
        print(f"ERROR: backend/ or frontend/ not found under {root}")
        print("Run this script from the financial-ai-platform project root.")
        sys.exit(1)

    print()
    print("  Financial AI Platform - Patch Applicator")
    print(f"  Project root : {root}")
    if args.whatif:
        print("  Mode         : DRY RUN  (no files written)")
    print()

    ok = 0

    for rel_path, b64_content, fix in PATCHES:
        target = root / rel_path.replace("/", os.sep)
        if args.whatif:
            status = "WOULD PATCH" if target.exists() else "WOULD CREATE"
            print(f"  [{status}]  {rel_path:<55}  {fix}")
            continue

        target.parent.mkdir(parents=True, exist_ok=True)

        if not args.no_backup and target.exists():
            bak = Path(str(target) + ".bak")
            target.rename(bak)

        content_bytes = base64.b64decode(b64_content.replace("\n", "").replace(" ", ""))
        # write as UTF-8 with LF line endings
        target.write_bytes(content_bytes)

        print(f"  [PATCHED]     {rel_path:<55}  {fix}")
        ok += 1

    print()
    if args.whatif:
        print("  DRY RUN complete - no files were written.")
    else:
        print(f"  {ok} file(s) patched successfully.")
        print()
        print("  Next steps:")
        print("    1. docker compose up -d")
        print("    2. ollama pull mistral:latest")
        print("    3. cd frontend && npm install && npm run dev")
        print("    4. python patch.py --whatif")
    print()


if __name__ == "__main__":
    main()
